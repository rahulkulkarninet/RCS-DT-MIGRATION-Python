                C.ContactID ,
                DC.[Date] ,
                DC.[Type] ,
                DC.[Phone] ,
                DC.[Outcome] ,
                DC.[Letter_Address] ,
                DC.[Document_Ref_No] ,
                DC.[Date_Printed] ,
                DC.[Payment_Code] ,
                DC.[Date_Sent_to_Client] ,
                DC.[Sms_Outcome] ,
                DC.[Poi_Key] ,
                DC.[Letter_Name] ,
