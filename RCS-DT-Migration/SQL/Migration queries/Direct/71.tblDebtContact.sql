        ( [AccountID] ,
          [ContactID] ,
          [DebtContactsTS] ,
          [Type] ,
          [Phone] ,
          [Outcome] ,
          [LetterAddress] ,
          [DocumentRefNo] ,
          [DatePrinted] ,
          [PaymentCode] ,
          [DateSenttoClient] ,
          [SmsOutcome] ,
          [PoiKey] ,
          [LetterName] ,
          [DateDequeued] ,
          [DateReturned] ,
          [MultiRecipientKey] ,
          [LetterTotalOutstanding] ,
          [SMSKey] ,
          [RequestCallDeletionDate] ,
          [RequestCallDeletionOperator] ,
          [EmailAddress] ,
          --[Solicited] ,
          [SenttoClient] ,
          [WorkdeskEmailKey] ,
          [AkEmailKey] ,
          [ActivityReportSent] ,
          [CreateID] ,
          [CreateSessionID] ,
          [CreateTS] ,
          [StatusID]
        )
